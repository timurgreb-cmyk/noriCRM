-- 1. Таблица Меню (menu)
CREATE TABLE IF NOT EXISTS menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    price INTEGER NOT NULL,
    category TEXT NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Таблица Диалогов (conversations)
CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT UNIQUE NOT NULL,
    messages JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- Функция для автоматического обновления времени изменения диалога
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Триггер для обновления updated_at при изменении диалога
CREATE OR REPLACE TRIGGER update_conversations_updated_at
BEFORE UPDATE ON conversations
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- 3. Таблица Заказов (orders)
-- Начинаем нумерацию заказов с 1000 для красивого вида на чеках
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    phone TEXT NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    items JSONB NOT NULL, -- Массив объектов [{id, name, quantity, price}]
    total INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'new', -- 'new', 'ready', 'completed'
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

